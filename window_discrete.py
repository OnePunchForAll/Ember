class QF:
    """Elements of a multiquadratic field Q(sqrt a, sqrt b): coefficients of 1, sqrt a, sqrt b, sqrt(ab)."""
    __slots__ = ('c', 'a', 'b')

    def __init__(self, c, a, b): self.c, self.a, self.b = tuple(Q(x) for x in c), a, b

    def __add__(self, o): return QF([x + y for x, y in zip(self.c, o.c)], self.a, self.b)

    def __sub__(self, o): return QF([x - y for x, y in zip(self.c, o.c)], self.a, self.b)

    def __mul__(self, o):
        a, b = self.a, self.b; x, y = self.c, o.c
        return QF([x[0] * y[0] + a * x[1] * y[1] + b * x[2] * y[2] + a * b * x[3] * y[3],
                   x[0] * y[1] + x[1] * y[0] + b * (x[2] * y[3] + x[3] * y[2]),
                   x[0] * y[2] + x[2] * y[0] + a * (x[1] * y[3] + x[3] * y[1]),
                   x[0] * y[3] + x[3] * y[0] + x[1] * y[2] + x[2] * y[1]], a, b)

    def is_one(self): return self.c == (1, 0, 0, 0)


