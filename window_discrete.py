def canonical_graph(n, edges, budget):
    """The lexicographically least adjacency string over vertex orders that sort vertices by degree."""
    adj = [[0] * n for _ in range(n)]; deg = [0] * n
    for u, v in edges: adj[u][v] = adj[v][u] = 1; deg[u] += 1; deg[v] += 1
    classes = {}
    for v in range(n): classes.setdefault(deg[v], []).append(v)
    groups = [classes[d] for d in sorted(classes)]
    best = None
    for parts in product(*[permutations(g) for g in groups]):
        order = [v for part in parts for v in part]; budget.use(n)
        s = ''.join(str(adj[order[i]][order[j]]) for i in range(n) for j in range(i + 1, n))
        if best is None or s < best: best = s
    return str(n) + ':' + best


def all_graphs(n, budget):
    """Every graph on n vertices up to isomorphism: {canonical code: edge list}."""
    pairs = list(combinations(range(n), 2)); out = {}
    for mask in range(1 << len(pairs)):
        edges = [pairs[i] for i in range(len(pairs)) if mask >> i & 1]
        code = canonical_graph(n, edges, budget)
        if code not in out: out[code] = edges
    return out


@family('graph_q', 'reconstruction', 'value',
        'For all graphs on n vertices up to isomorphism: their number, and whether their decks (multisets of '
        'vertex-deleted subgraphs up to isomorphism) are pairwise different.')
def fam_reconstruction(params, budget):
    need(set(params) == {'n'}, 'reconstruction fields'); n = integer(params['n'], 3, 6)
    graphs = all_graphs(n, budget); decks = set()
    for code, edges in graphs.items():
        deck = []
        for v in range(n):
            keep = [u for u in range(n) if u != v]; idx = {u: i for i, u in enumerate(keep)}
            sub = [(idx[a], idx[b]) for a, b in edges if a != v and b != v]
            deck.append(canonical_graph(n - 1, sub, budget))
        decks.add(tuple(sorted(deck)))
    return dict(graphs=len(graphs), distinct_decks=len(decks) == len(graphs))


def _oriented(n, budget):
    """Every oriented graph on n labeled vertices as out-neighbour sets (each pair: none, u -> v or v -> u)."""
    pairs = list(combinations(range(n), 2))
    for code in product((0, 1, 2), repeat=len(pairs)):
        budget.use(n)
        out = [set() for _ in range(n)]
        for (u, v), c in zip(pairs, code):
            if c == 1: out[u].add(v)
            elif c == 2: out[v].add(u)
        yield out


def _girth_directed(out, n):
    best = None
    for s in range(n):
        dist = {s: 0}; frontier = [s]
        while frontier:
            nxt = []
            for u in frontier:
                for v in out[u]:
                    if v == s:
                        L = dist[u] + 1; best = L if best is None or L < best else best
                    elif v not in dist: dist[v] = dist[u] + 1; nxt.append(v)
            frontier = nxt
    return best


@family('graph_q', 'oriented_census', 'value',
        'Over every oriented graph on n labeled vertices: how many violate the property (second_neighborhood: no '
        'vertex has at least as many vertices at distance 2 as at distance 1; caccetta: minimum out-degree r but no '
        'directed cycle of length at most ceil(n / r)).')
def fam_oriented(params, budget):
    need(set(params) == {'n', 'property', 'r'}, 'oriented fields'); n = integer(params['n'], 2, 5)
    prop, r = params['property'], integer(params['r'], 0, 4); bad = 0; checked = 0
    for out in _oriented(n, budget):
        if prop == 'second_neighborhood':
            checked += 1
            if not any(len({w for u in out[v] for w in out[u]} - out[v] - {v}) >= len(out[v]) for v in range(n)): bad += 1
        elif prop == 'caccetta':
            if min(len(o) for o in out) < r or r == 0: continue
            checked += 1; g = _girth_directed(out, n)
            if g is None or g > -(-n // r): bad += 1
        else: raise Invalid('unknown property')
    return dict(checked=checked, violations=bad)


def _has_cycle_length(n, adj, L, budget):
    """Whether the graph has a simple cycle of exactly L vertices (DFS from each least vertex)."""
    for s in range(n):
        stack = [(s, [s])]
        while stack:
            v, path = stack.pop(); budget.use()
            for u in adj[v]:
                if u == s and len(path) == L: return True
                if u > s and u not in path and len(path) < L: stack.append((u, path + [u]))
    return False


