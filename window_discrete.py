def pebbling_number(n, adj, budget, cap=40):
    """The least p such that every distribution of p pebbles can move a pebble to any target (moves take two
    pebbles off a vertex and put one on a neighbour)."""
    from functools import lru_cache
    for p in range(1, cap + 1):
        ok = True
        for target in range(n):
            @lru_cache(maxsize=None)
            def solvable(conf):
                budget.use()
                if conf[target] >= 1: return True
                for v in range(n):
                    if conf[v] >= 2:
                        for u in adj[v]:
                            c = list(conf); c[v] -= 2; c[u] += 1
                            if solvable(tuple(c)): return True
                return False
            def dists(k, i):
                if i == n - 1: yield (k,); return
                for a in range(k + 1):
                    for rest in dists(k - a, i + 1): yield (a,) + rest
            for conf in dists(p, 0):
                if not solvable(conf): ok = False; break
            if not ok: break
        if ok: return p
    raise Invalid('pebbling bound')


