@family('knot_q', 'jones', 'value',
        'The Jones polynomial of the knot given by its planar diagram code (crossings [a, b, c, d] of arc labels), from '
        'the Kauffman bracket state sum and the writhe: coefficients from the lowest power of t, with that power.')
def fam_jones(params, budget):
    need(set(params) == {'pd'}, 'knot fields'); pd = params['pd']
    need(type(pd) is list and 2 <= len(pd) <= 14 and all(type(x) is list and len(x) == 4 for x in pd), 'crossings')
    m = 2 * len(pd); labels = [a for x in pd for a in x]
    need(all(type(a) is int for a in labels) and sorted(labels) == sorted(list(range(1, m + 1)) * 2),
         'every arc 1..2n appears exactly twice')
    need(all(c == a % m + 1 and (b - d) % m in (1, m - 1) for a, b, c, d in pd),
         'each crossing lists the incoming under-arc first, counterclockwise, with consecutive arcs')
    arcs = sorted(set(labels))
    # bracket in A: states smooth each crossing [a, b, c, d] as A (a-b, c-d) or A^-1 (a-d, b-c)
    poly = {}
    for state in product((0, 1), repeat=len(pd)):
        budget.use(len(pd))
        parent = {a: a for a in arcs}
        def find(x):
            while parent[x] != x: parent[x] = parent[parent[x]]; x = parent[x]
            return x
        for (a, b, c, d), s in zip(pd, state):
            pairs = ((a, b), (c, d)) if s == 0 else ((a, d), (b, c))
            for u, v in pairs: parent[find(u)] = find(v)
        loops = len({find(a) for a in arcs}); na = state.count(0); nb = len(pd) - na
        # A^(na - nb) (-A^2 - A^-2)^(loops - 1)
        term = {na - nb: 1}
        for _ in range(loops - 1):
            nxt = {}
            for e, c in term.items():
                nxt[e + 2] = nxt.get(e + 2, 0) - c; nxt[e - 2] = nxt.get(e - 2, 0) - c
            term = nxt
        for e, c in term.items(): poly[e] = poly.get(e, 0) + c
    poly = {e: c for e, c in poly.items() if c}
    # writhe: [a, b, c, d] (under-strand a -> c) is positive when the over-strand runs d -> b, i.e. b = d + 1 (mod 2n)
    w = sum(1 if (b - d) % m == 1 else -1 for a, b, c, d in pd)
    # V(t) = (-A^3)^(-w) <K> with A = t^(-1/4)
    sign = -1 if w % 2 else 1
    V = {}
    for e, c in poly.items():
        k = e - 3 * w  # power of A
        need(k % 4 == 0, 'the bracket is not a polynomial in t for a knot')
        V[-k // 4] = V.get(-k // 4, 0) + sign * c
    lo, hi = min(V), max(V)
    return dict(lowest_power=lo, coefficients=[V.get(i, 0) for i in range(lo, hi + 1)])


