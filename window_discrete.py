def _word(w, ngens):
    need(type(w) is list and all(type(x) is int and x != 0 and abs(x) <= ngens for x in w), 'word of generator indices')
    return w


def coset_enumerate(ngens, relators, limit, budget):
    """Todd-Coxeter (HLT) enumeration of the cosets of the trivial subgroup: the group order, or None past the limit."""
    cols = [g for i in range(1, ngens + 1) for g in (i, -i)]
    table = [{c: None for c in cols}]; live = [True]
    parent = [0]
    def find(c):
        while parent[c] != c: parent[c] = parent[parent[c]]; c = parent[c]
        return c
    def define(c, x):
        need(len(table) < limit, 'coset limit')
        d = len(table); table.append({g: None for g in cols}); live.append(True); parent.append(d)
        table[c][x] = d; table[d][-x] = c; budget.use(len(cols))
        return d
    queue = []
    def coincidence(a, b):
        queue.append((a, b))
        while queue:
            a, b = queue.pop(); a, b = find(a), find(b)
            if a == b: continue
            if a > b: a, b = b, a
            parent[b] = a; live[b] = False
            for x in cols:
                t = table[b][x]
                if t is None: continue
                table[b][x] = None
                if table[t].get(-x) == b: table[t][-x] = None
                ta = table[a][x]
                if ta is None: table[a][x] = t; table[t][-x] = a
                else: queue.append((ta, t))
    def scan_and_fill(c, w):
        budget.use(len(w))
        f, i, b, j = c, 0, c, len(w) - 1
        while True:
            while i <= j and table[f][w[i]] is not None: f = table[f][w[i]]; i += 1
            if i > j:
                if f != c: coincidence(f, c)
                return
            while j >= i and table[b][-w[j]] is not None: b = table[b][-w[j]]; j -= 1
            if j < i: coincidence(f, b); return
            if i == j:
                table[f][w[i]] = b; table[b][-w[i]] = f; return
            define(f, w[i])
    c = 0
    while c < len(table):
        if live[c] and find(c) == c:
            for r in relators:
                if not live[c] or find(c) != c: break
                scan_and_fill(c, r)
            if live[c] and find(c) == c:
                for x in cols:
                    if table[c][x] is None: define(c, x)
        c += 1
    return sum(1 for i in range(len(table)) if live[i] and find(i) == i)


