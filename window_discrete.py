def chromatic_index(n, adj, budget):
    edges = sorted({(u, v) for u in range(n) for v in adj[u] if u < v}); D = max(len(a) for a in adj)
    inc = [[] for _ in range(n)]
    for i, (u, v) in enumerate(edges): inc[u].append(i); inc[v].append(i)
    for k in (D, D + 1):
        col = [-1] * len(edges)
        def go(i):
            budget.use()
            if i == len(edges): return True
            u, v = edges[i]; used = {col[j] for j in inc[u] + inc[v] if col[j] >= 0}
            for c in range(k):
                if c not in used:
                    col[i] = c
                    if go(i + 1): return True
            col[i] = -1; return False
        if go(0): return k
    raise Invalid('Vizing bound exceeded')


