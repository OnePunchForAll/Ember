def _hadwiger(n, adj, budget):
    """The largest t such that K_t is a minor: branch sets as connected blocks of a set partition (small n)."""
    best = 1
    def partitions(items):
        if not items: yield []; return
        first, rest = items[0], items[1:]
        for p in partitions(rest):
            yield [[first]] + p
            for i in range(len(p)): yield p[:i] + [[first] + p[i]] + p[i + 1:]
    def connected(block):
        seen = {block[0]}; stack = [block[0]]; S = set(block)
        while stack:
            v = stack.pop()
            for u in adj[v] & S:
                if u not in seen: seen.add(u); stack.append(u)
        return len(seen) == len(S)
    for p in partitions(list(range(n))):
        budget.use(len(p))
        blocks = [b for b in p]
        # every block need not be used: take the connected blocks pairwise touching
        conn = [b for b in blocks if connected(b)]
        for size in range(len(conn), best, -1):
            for chosen in combinations(conn, size):
                if all(any(u in adj[v] for v in a for u in b) for a, b in combinations(chosen, 2)):
                    best = size; break
            if best >= size: break
    return best


