def _reduce(w):
    out = []
    for x in w:
        if out and out[-1] == -x: out.pop()
        else: out.append(x)
    return out


def _cyc_reduce(w):
    w = _reduce(w)
    while len(w) >= 2 and w[0] == -w[-1]: w = w[1:-1]
    return w


