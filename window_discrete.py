def _mpoly(p, nvars):
    """A polynomial as {exponent tuple: rational}: from [[coefficient, [exponents]], ...]."""
    need(type(p) is list and len(p) <= 400, 'polynomial terms'); out = {}
    for c, e in p:
        need(type(e) is list and len(e) == nvars and all(type(x) is int and 0 <= x <= 60 for x in e), 'exponents')
        k = tuple(e); out[k] = out.get(k, Q(0)) + _rat(c)
    return {k: v for k, v in out.items() if v}


def _padd(a, b):
    out = dict(a)
    for k, v in b.items():
        out[k] = out.get(k, Q(0)) + v
        if not out[k]: del out[k]
    return out


def _pmul(a, b, budget):
    out = {}
    for k1, v1 in a.items():
        for k2, v2 in b.items():
            k = tuple(x + y for x, y in zip(k1, k2)); out[k] = out.get(k, Q(0)) + v1 * v2
    budget.use(len(a) * len(b))
    return {k: v for k, v in out.items() if v}


def _compose(f, G, budget):
    """f(G_1, ..., G_n) for a polynomial f and a list of polynomials G."""
    n = len(G); out = {}; cache = {}
    def power(i, e):
        if (i, e) not in cache:
            r = {(0,) * n: Q(1)}
            for _ in range(e): r = _pmul(r, G[i], budget); need(len(r) <= 20_000, 'composition size')
            cache[(i, e)] = r
        return cache[(i, e)]
    for k, c in f.items():
        term = {(0,) * n: c}
        for i, e in enumerate(k):
            if e: term = _pmul(term, power(i, e), budget)
        out = _padd(out, term)
    return out


