@family('algebra_q', 'casas_alvero', 'value',
        'Among monic integer polynomials of the given degree with other coefficients of size at most h_max: those that '
        'share a root with each of their first degree - 1 derivatives without being (x - a)^degree (counterexamples to '
        'Casas-Alvero); expected none.')
def fam_casas_alvero(params, budget):
    need(set(params) == {'degree', 'h_max'}, 'Casas-Alvero fields')
    d, H = integer(params['degree'], 2, 8), integer(params['h_max'], 1, 4)
    need((2 * H + 1) ** d <= 400_000, 'enumeration bound')
    out = []
    def gcd_deg(a, b):
        a = [Q(x) for x in a]; b = [Q(x) for x in b]
        while any(b):
            while b and b[-1] == 0: b.pop()
            r = list(a)
            while len(r) >= len(b) and any(r):
                c = r[-1] / b[-1]; s = len(r) - len(b)
                for i, x in enumerate(b): r[s + i] -= c * x
                r.pop()
                while r and r[-1] == 0: r.pop()
            a, b = b, r
        return len(a) - 1
    for cs in product(range(-H, H + 1), repeat=d):
        f = list(cs) + [1]; budget.use(d * d)
        g = f; ok = True
        for k in range(1, d):
            g = [i * c for i, c in enumerate(g)][1:]
            if gcd_deg(f, g) < 1: ok = False; break
        if not ok: continue
        # (x - a)^d: then c_(d-1) = -d a and the polynomial equals (x + c_(d-1)/d)^d
        a = Q(-f[d - 1], d)
        expand = [comb(d, i) * (-a) ** (d - i) for i in range(d + 1)]
        if [Q(c) for c in f] != expand: out.append(f)
    return out


# ------------------------------------------------------------- curves over finite fields

@family('variety_q', 'elliptic_ap', 'value',
        'For E: y^2 = x^3 + a x + b and each prime 3 < p <= p_max not dividing its discriminant: a_p = p + 1 - #E(F_p) '
        '(projective points), with the Hasse bound a_p^2 <= 4p checked; and the product of #E(F_p)/p over these primes '
        'as decimal bounds (Birch and Swinnerton-Dyer\'s original numerical evidence).')
def fam_elliptic_ap(params, budget):
    need(set(params) == {'a', 'b', 'p_max'}, 'curve fields')
    a, b, P = integer(params['a'], -10 ** 6, 10 ** 6), integer(params['b'], -10 ** 6, 10 ** 6), integer(params['p_max'], 5, 5000)
    disc = -16 * (4 * a ** 3 + 27 * b * b); need(disc != 0, 'singular curve')
    aps = {}; lo, hi = Q(1), Q(1)
    for p in range(5, P + 1):
        if not is_prime(p, budget) or disc % p == 0: continue
        budget.use(p)
        s = sum(jacobi((x * x * x + a * x + b) % p, p) for x in range(p))
        ap = -s; need(ap * ap <= 4 * p, 'Hasse bound fails'); aps[str(p)] = ap
        lo *= Q(p + 1 - ap, p)
    v = lo
    return dict(ap=aps, product=[v.numerator.bit_length() - v.denominator.bit_length(), str(round(float(v), 6))])


@family('variety_q', 'rational_points', 'witness',
        'The witness lists rational points (x, y) on y^2 = x^3 + a x + b, each checked exactly.')
def fam_rational_points(params, witness, budget):
    need(set(params) == {'a', 'b'}, 'curve fields'); a, b = integer(params['a']), integer(params['b'])
    need(type(witness) is list and 1 <= len(witness) <= 1000, 'points')
    for pt in witness:
        x, y = _pt(pt); budget.use(); need(y * y == x ** 3 + a * x + b, 'a point is not on the curve')
    return dict(points=len(witness))


@family('variety_q', 'point_count', 'value',
        'The number of points over F_p of the projective hypersurface given by a homogeneous integer polynomial in '
        'n + 1 variables (terms [coefficient, [exponents]]), by exhaustive count.')
def fam_point_count(params, budget):
    need(set(params) == {'poly', 'nvars', 'p'}, 'point count fields')
    k, p = integer(params['nvars'], 2, 4), integer(params['p'], 2, 200); need(is_prime(p, budget), 'prime p')
    need(p ** k <= 5_000_000, 'enumeration bound'); f = _mpoly(params['poly'], k)
    degs = {sum(e) for e in f}; need(len(degs) == 1, 'homogeneous')
    count = 0
    for v in product(range(p), repeat=k):
        if not any(v): continue
        # one representative per line: first nonzero coordinate 1
        if v[next(i for i in range(k) if v[i])] != 1: continue
        budget.use(len(f))
        if sum(int(c) * _prod(x ** e for x, e in zip(v, ex)) for ex, c in f.items()) % p == 0: count += 1
    return count


def _prod(xs):
    out = 1
    for x in xs: out *= x
    return out
