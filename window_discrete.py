@family('graph_q', 'srg_feasible', 'value',
        'The standard feasibility conditions for a strongly regular graph (v, k, lambda, mu): the counting identity, '
        'integral eigenvalue multiplicities, the Krein conditions and the absolute bound, each true or false.')
def fam_srg(params, budget):
    need(set(params) == {'v', 'k', 'l', 'm'}, 'SRG fields')
    v, k, l, m = (integer(params[x], 0, 10 ** 7) for x in ('v', 'k', 'l', 'm'))
    need(0 < k < v - 1, 'parameters')
    count = k * (k - l - 1) == (v - k - 1) * m
    D = (l - m) ** 2 + 4 * (k - m); rD = isqrt(D)
    out = dict(counting=count)
    # eigenvalues r, s = (l - m +- sqrt D) / 2 with multiplicities f, g
    num = 2 * k + (v - 1) * (l - m)
    if rD * rD == D:
        r2, s2 = (l - m) + rD, (l - m) - rD  # 2r, 2s
        f_num = (v - 1) * (-s2) - 2 * k; f_den = r2 - s2
        integral = f_den != 0 and f_num % f_den == 0
        out['multiplicities_integral'] = integral
        if integral:
            f = f_num // f_den; g = v - 1 - f; r, s = Q(r2, 2), Q(s2, 2)
            out['krein'] = ((r + 1) * (k + r + 2 * r * s) <= (k + r) * (s + 1) ** 2 and
                            (s + 1) * (k + s + 2 * r * s) <= (k + s) * (r + 1) ** 2)
            out['absolute_bound'] = v <= f * (f + 3) // 2 and v <= g * (g + 3) // 2
            out['eigenvalues'] = [str(r), str(s)]; out['multiplicities'] = [f, g]
    else:
        out['multiplicities_integral'] = num == 0 and (v - 1) % 2 == 0  # the conference case
        out['conference'] = num == 0
    return out


def _cliques(n, adj, s, budget):
    """Whether the graph has a clique of size s (Bron-Kerbosch with pivoting, stopping at s)."""
    found = [False]
    def bk(R, P, X):
        budget.use()
        if found[0]: return
        if len(R) >= s: found[0] = True; return
        if len(R) + len(P) < s: return
        pivot = max(P | X, key=lambda u: len(adj[u] & P)) if P | X else None
        for v in list(P - (adj[pivot] if pivot is not None else set())):
            bk(R | {v}, P & adj[v], X & adj[v]); P = P - {v}; X = X | {v}
            if found[0]: return
    bk(set(), set(range(n)), set())
    return found[0]


@family('graph_q', 'ramsey_coloring', 'witness',
        'The witness is a graph on n vertices (the edges of the first color) with no clique of size s and no '
        'independent set of size t: so R(s, t) > n.')
def fam_ramsey(params, witness, budget):
    need(set(params) == {'n', 's', 't'}, 'Ramsey fields')
    n, s, t = integer(params['n'], 2, 200), integer(params['s'], 2, 8), integer(params['t'], 2, 8)
    n2, adj = graph_of(dict(n=n, edges=witness), budget)
    comp = [set(range(n)) - adj[v] - {v} for v in range(n)]
    need(not _cliques(n, adj, s, budget), 'a clique of size s in the first color')
    need(not _cliques(n, comp, t, budget), 'a clique of size t in the second color')
    return dict(lower_bound=n + 1)


def _rooted_clique(n, adj, size, budget):
    """Whether a vertex-transitive graph (adjacency as bitmasks) has a clique of the size: by transitivity, one
    through vertex 0. Branch and bound; a greedy partition of the candidates into independent sets bounds the rest."""
    def bound(P):
        classes = 0
        while P:
            classes += 1; Q = P
            while Q:
                v = Q.bit_length() - 1; Q &= ~(1 << v); P &= ~(1 << v); Q &= ~adj[v]
        return classes
    def go(have, P):
        budget.use()
        if have >= size: return True
        if have + bin(P).count('1') < size or have + bound(P) < size: return False
        while P:
            v = P.bit_length() - 1; P &= ~(1 << v)
            if go(have + 1, P & adj[v]): return True
        return False
    return go(1, adj[0])


@family('graph_q', 'circulant_ramsey', 'witness',
        'The witness is the connection set of a circulant graph on n vertices (distances d, 1 <= d <= n/2, joining v '
        'to v + d and v - d) with no clique of size s and no independent set of size t, checked through vertex 0 by '
        'vertex transitivity: so R(s, t) > n.')
def fam_circulant_ramsey(params, witness, budget):
    need(set(params) == {'n', 's', 't'}, 'Ramsey fields')
    n, s, t = integer(params['n'], 3, 400), integer(params['s'], 3, 8), integer(params['t'], 3, 32)
    need(type(witness) is list and witness == sorted(set(witness)) and all(type(d) is int and 1 <= d <= n // 2 for d in witness),
         'distances 1..n/2, sorted, distinct')
    S = set(witness) | {n - d for d in witness}
    adj = [sum(1 << ((v + d) % n) for d in S) for v in range(n)]
    full = (1 << n) - 1
    comp = [full & ~adj[v] & ~(1 << v) for v in range(n)]
    need(not _rooted_clique(n, adj, s, budget), 'a clique of size s through vertex 0')
    need(not _rooted_clique(n, comp, t, budget), 'an independent set of size t through vertex 0')
    return dict(lower_bound=n + 1, degree=len(S))


def _hom_count(Hn, Hedges, n, adj, budget):
    """The number of homomorphisms from a small graph H into G."""
    order = list(range(Hn)); count = 0
    def go(i, phi):
        nonlocal count
        budget.use()
        if i == Hn: count += 1; return
        for x in range(n):
            if all((phi[j] in adj[x]) for j in range(i) if (j, i) in Hset or (i, j) in Hset):
                phi.append(x); go(i + 1, phi); phi.pop()
    Hset = {(min(a, b), max(a, b)) for a, b in Hedges}
