def hadamard_constructible(k_max):
    """Orders 4k <= 4 k_max reached from 1 and 2 by Sylvester doubling, Paley I (q + 1, q = 3 mod 4 a prime power),
    Paley II (2(q + 1), q = 1 mod 4) and Kronecker products."""
    top = 4 * k_max; have = {1, 2}
    for q in range(2, top + 1):
        pp = _prime_power(q)
        if pp and q % 4 == 3 and q + 1 <= top: have.add(q + 1)
        if pp and q % 4 == 1 and 2 * (q + 1) <= top: have.add(2 * (q + 1))
    changed = True
    while changed:
        changed = False
        for a in sorted(have):
            for b in sorted(have):
                if a * b <= top and a * b not in have: have.add(a * b); changed = True
    return have


