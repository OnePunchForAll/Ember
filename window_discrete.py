@family('circuit_q', 'isomorphic', 'value',
        'Whether the two graphs (at most 64 vertices) are isomorphic: colour refinement separates most '
        'non-isomorphic pairs, and an exhaustive backtracking search over colour classes decides the rest.')
def fam_isomorphic(params, budget):
    need(set(params) == {'G', 'H'}, 'isomorphism fields')
    gn, gadj = graph_of(params['G'], budget); hn, hadj = graph_of(params['H'], budget)
    need(gn <= 64 and hn <= 64, 'graph size for the isomorphism search')
    if gn != hn or sum(map(len, gadj)) != sum(map(len, hadj)): return False
    n = gn
    # colour refinement on the disjoint union; different colour histograms mean non-isomorphic
    adj = [set(a) for a in gadj] + [{v + n for v in a} for a in hadj]
    colour = [len(a) for a in adj]
    while True:
        budget.use(2 * n)
        sig = [(colour[v], tuple(sorted(colour[u] for u in adj[v]))) for v in range(2 * n)]
        names = {k: i for i, k in enumerate(sorted(set(sig)))}
        new = [names[k] for k in sig]
        if len(set(new)) == len(set(colour)): colour = new; break
        colour = new
    if sorted(colour[:n]) != sorted(colour[n:]): return False
    # backtracking over colour classes, smallest classes first, keeping adjacency with mapped vertices
    order = sorted(range(n), key=lambda v: (sum(1 for u in range(n) if colour[u] == colour[v]), -len(gadj[v]), v))
    image = {}; used = set()
    def go(i):
        budget.use()
        if i == n: return True
        v = order[i]
        for w in range(n):
            if w in used or colour[w + n] != colour[v]: continue
            if all((u in gadj[v]) == (image[u] in hadj[w]) for u in image):
                image[v] = w; used.add(w)
                if go(i + 1): return True
                del image[v]; used.discard(w)
        return False
    return go(0)


