def _posets(n, budget):
    """Every partial order on n labeled elements as relation bitmasks (transitively closed DAGs)."""
    pairs = [(i, j) for i in range(n) for j in range(n) if i != j]
    def closed(rel):
        for (a, b) in rel:
            for (c, d) in rel:
                if b == c and (a, d) not in rel: return False
        return True
    out = []
    def go(i, rel):
        budget.use()
        if i == len(pairs):
            if closed(rel): out.append(frozenset(rel))
            return
        a, b = pairs[i]
        go(i + 1, rel)
        if (b, a) not in rel: go(i + 1, rel | {(a, b)})
    go(0, frozenset())
    return out


@family('setsys_q', 'balanced_pair', 'value',
        'Over every partial order on n labeled elements that is not a chain: the least, over the orders, of the largest '
        'balance min(p, 1 - p) of a pair, p the probability that x precedes y in a uniform linear extension (the '
        '1/3-2/3 conjecture says at least 1/3).')
def fam_balanced_pair(params, budget):
    need(set(params) == {'n'}, 'poset fields'); n = integer(params['n'], 2, 5)
    worst = None
    for rel in _posets(n, budget):
        below = [0] * n
        for a, b in rel: below[b] |= 1 << a
        # linear extensions counted by subsets; ext_before[x][y]: extensions with x before y
        cnt = {0: 1}
        for mask in range(1 << n):
            if mask not in cnt: continue
            for v in range(n):
                if not mask >> v & 1 and (below[v] & ~mask) == 0:
                    cnt[mask | 1 << v] = cnt.get(mask | 1 << v, 0) + cnt[mask]
        total = cnt.get((1 << n) - 1, 0)
        incomparable = [(x, y) for x, y in combinations(range(n), 2) if (x, y) not in rel and (y, x) not in rel]
        if not incomparable: continue
        best = Q(0)
        for x, y in incomparable:
            # extensions with x before y: count linear extensions of rel + (x, y)
            b2 = list(below); b2[y] |= 1 << x
            c2 = {0: 1}
            for mask in range(1 << n):
                if mask not in c2: continue
                for v in range(n):
                    if not mask >> v & 1 and (b2[v] & ~mask) == 0:
                        c2[mask | 1 << v] = c2.get(mask | 1 << v, 0) + c2[mask]
            p = Q(c2.get((1 << n) - 1, 0), total); budget.use(1 << n)
            best = max(best, min(p, 1 - p))
        worst = best if worst is None or best < worst else worst
    return [worst.numerator, worst.denominator]


