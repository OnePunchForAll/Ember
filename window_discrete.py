def _perm_group(gens, budget, limit=5000):
    """All elements of the permutation group generated by gens (tuples), by closure."""
    need(type(gens) is list and 1 <= len(gens) <= 6, 'generators')
    m = len(gens[0])
    gens = [tuple(g) for g in gens]
    need(all(sorted(g) == list(range(m)) for g in gens), 'permutations of 0..m-1')
    ident = tuple(range(m)); elems = {ident: 0}; order = [ident]; i = 0
    while i < len(order):
        g = order[i]; i += 1
        for s in gens:
            h = tuple(s[x] for x in g)
            if h not in elems:
                elems[h] = len(order); order.append(h); budget.use(m)
                need(len(order) <= limit, 'group order bound')
    return order, elems, gens


def graph_of(spec, budget):
    """(n, adjacency sets) of a graph given by edges or by name."""
    need(type(spec) is dict, 'graph')
    if 'edges' in spec:
        n = integer(spec['n'], 1, 2000); adj = [set() for _ in range(n)]
        for u, v in spec['edges']:
            need(type(u) is int and type(v) is int and 0 <= u < n and 0 <= v < n and u != v, 'edge')
            adj[u].add(v); adj[v].add(u)
        return n, adj
    name = spec.get('named')
    if name == 'petersen': return graph_of(dict(named='gp', n=5, k=2), budget)
    if name == 'gp':
        m, k = integer(spec['n'], 3, 500), integer(spec['k'], 1)
        need(k < m / 2, 'generalized Petersen parameter')
        edges = [[i, (i + 1) % m] for i in range(m)] + [[i, i + m] for i in range(m)] + \
                [[m + i, m + (i + k) % m] for i in range(m)]
        return graph_of(dict(n=2 * m, edges=edges), budget)
    if name == 'cycle':
        m = integer(spec['n'], 3, 2000); return graph_of(dict(n=m, edges=[[i, (i + 1) % m] for i in range(m)]), budget)
    if name == 'complete':
        m = integer(spec['n'], 1, 200); return graph_of(dict(n=m, edges=[list(e) for e in combinations(range(m), 2)]), budget)
    if name == 'paley':
        q = integer(spec['q'], 5, 2000); need(is_prime(q, budget) and q % 4 == 1, 'prime q = 1 mod 4')
        sq = {x * x % q for x in range(1, q)}
        return graph_of(dict(n=q, edges=[[i, j] for i, j in combinations(range(q), 2) if (j - i) % q in sq]), budget)
    if name == 'hypercube':
        d = integer(spec['d'], 1, 10)
        return graph_of(dict(n=1 << d, edges=[[v, v ^ (1 << b)] for v in range(1 << d) for b in range(d) if v < v ^ (1 << b)]), budget)
    if name == 'cayley':
        order, elems, gens = _perm_group(spec['perms'], budget)
        edges = set()
        for g in order:
            for s in gens:
                h = tuple(s[x] for x in g); a, b = elems[g], elems[h]
                if a != b: edges.add((min(a, b), max(a, b)))
        return graph_of(dict(n=len(order), edges=[list(e) for e in sorted(edges)]), budget)
    raise Invalid('unknown graph ' + str(name))


def _proper(adj, colors):
    return all(colors[u] != colors[v] for u in range(len(adj)) for v in adj[u])


def chromatic_number(n, adj, budget, cap=None):
    """Exact chromatic number by backtracking in DSATUR order."""
    best = [n + 1 if cap is None else cap + 1]
    colors = [-1] * n
    def pick():
        best_v, key = -1, None
        for v in range(n):
            if colors[v] < 0:
                sat = len({colors[u] for u in adj[v] if colors[u] >= 0})
                k = (sat, len(adj[v]))
                if key is None or k > key: best_v, key = v, k
        return best_v
    def go(used):
        budget.use(n)
        if used >= best[0]: return
        v = pick()
        if v < 0: best[0] = used; return
        banned = {colors[u] for u in adj[v]}
        for c in range(used + 1):
            if c in banned: continue
            if c == used and used + 1 >= best[0]: break
            colors[v] = c; go(max(used, c + 1)); colors[v] = -1
    go(0)
    return best[0]


