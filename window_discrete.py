def _upoly_mod(p, q):
    """An integer polynomial (lowest degree first) reduced mod q, trimmed."""
    r = [c % q for c in p]
    while len(r) > 1 and r[-1] == 0: r.pop()
    return r


def _pmod_divmod(a, b, q):
    a = list(a); inv = pow(b[-1], -1, q); out = [0] * max(1, len(a) - len(b) + 1)
    while len(a) >= len(b) and any(a):
        c = a[-1] * inv % q; s = len(a) - len(b); out[s] = c
        for i, x in enumerate(b): a[s + i] = (a[s + i] - c * x) % q
        while a and a[-1] == 0: a.pop()
    return out, a or [0]


def _pmod_gcd(a, b, q):
    a, b = _upoly_mod(a, q), _upoly_mod(b, q)
    while any(b):
        _, r = _pmod_divmod(a, b, q); a, b = b, _upoly_mod(r, q)
    return a


def _pmod_mul(a, b, q):
    out = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b): out[i + j] = (out[i + j] + x * y) % q
    return out


def _pmod_powmod(base, e, m, q):
    result = [1]; base = _pmod_divmod(base, m, q)[1]
    while e:
        if e & 1: result = _pmod_divmod(_pmod_mul(result, base, q), m, q)[1]
        base = _pmod_divmod(_pmod_mul(base, base, q), m, q)[1]; e >>= 1
    return result


def factor_degrees_mod(f, q):
    """The degrees of the irreducible factors of a squarefree polynomial mod a prime q (distinct-degree factorization)."""
    f = _upoly_mod(f, q); inv = pow(f[-1], -1, q); f = [c * inv % q for c in f]
    degs = []; x = [0, 1]; h = x; d = 0
    while len(f) - 1 >= 2 * (d + 1):
        d += 1; h = _pmod_powmod(h, q, f, q)
        diff = list(h) + [0] * (2 - len(h)); diff[1] = (diff[1] - 1) % q
        g = _pmod_gcd(f, _upoly_mod(diff, q), q)
        if len(g) > 1:
            degs += [d] * ((len(g) - 1) // d); f = _pmod_divmod(f, g, q)[0]; h = _pmod_divmod(h, f, q)[1] if len(f) > 1 else [0]
    if len(f) > 1: degs.append(len(f) - 1)
    return sorted(degs)


def _disc(f):
    """The discriminant of an integer polynomial (lowest degree first), via the resultant with its derivative."""
    df = [i * c for i, c in enumerate(f)][1:]
    n = len(f) - 1
    R = _resultant([Q(c) for c in f], [Q(c) for c in df])
    return int(R * (-1) ** (n * (n - 1) // 2) / f[-1])


def _resultant(a, b):
    """Resultant of two polynomials (lowest degree first) by the Euclidean algorithm over Q."""
    a, b = list(a), list(b); res = Q(1)
    while True:
        while a and a[-1] == 0: a.pop()
        while b and b[-1] == 0: b.pop()
        if len(b) == 1: return res * b[0] ** (len(a) - 1)
        if not b: return Q(0)
        da, db = len(a) - 1, len(b) - 1
        r = list(a)
        while len(r) >= len(b) and any(r):
            c = r[-1] / b[-1]; s = len(r) - len(b)
            for i, x in enumerate(b): r[s + i] -= c * x
            r.pop()
            while r and r[-1] == 0: r.pop()
        dr = len(r) - 1 if r else -1
        if dr < 0: return Q(0)
        res *= (-1) ** (da * db) * b[-1] ** (da - dr)
        a, b = b, r


def _rational_roots(g):
    """The integer roots of a monic integer polynomial (lowest degree first)."""
    out = set(); c0 = abs(g[0])
    if c0 == 0: out.add(0); return out
    for d in range(1, isqrt(c0) + 1):
        if c0 % d == 0:
            for r in (d, -d, c0 // d, -(c0 // d)):
                if sum(c * r ** i for i, c in enumerate(g)) == 0: out.add(r)
    return out


def _irreducible(f, budget):
    """Whether a monic integer polynomial of degree 2..5 is irreducible over Q: no root and no monic quadratic factor
    (Gauss: a factorization over Q gives one over Z with monic factors)."""
    n = len(f) - 1
    if _rational_roots(f): return False
    if n < 4: return True
    B = 1 + max(abs(c) for c in f[:-1])  # Cauchy: every root has |z| < B
    for u in range(-2 * B, 2 * B + 1):
        for v in range(-B * B, B * B + 1):
            if v == 0 or f[0] % v: continue
            budget.use(n)
            r = [Q(c) for c in f]
            q = [Q(v), Q(u), Q(1)]
            while len(r) >= 3:
                c = r[-1]; sh = len(r) - 3
                for i in range(3): r[sh + i] -= c * q[i]
                r.pop()
            if not any(r): return False
    return True


def _q_square(x):
    x = Q(x)
    return x >= 0 and isqrt(x.numerator) ** 2 == x.numerator and isqrt(x.denominator) ** 2 == x.denominator


@family('algebra_q', 'galois_group', 'value',
        'The Galois group over Q of the listed monic irreducible integer polynomial of degree 3, 4 or 5 (irreducibility '
        'checked exactly). Degree 3: the discriminant decides S3 or C3. Degree 4: the resolvent cubic and the '
        'Kappe-Warren test decide S4, A4, D4, C4 or V4. Degree 5: a Frobenius transposition at a prime up to p_max gives '
        'S5; a square discriminant with a 3-cycle gives A5; otherwise null (the solvable groups are not decided here).')
def fam_galois(params, budget):
    need(set(params) == {'poly', 'p_max'}, 'Galois fields'); f = params['poly']; P = integer(params['p_max'], 5, 2000)
    need(type(f) is list and 4 <= len(f) <= 6 and all(type(c) is int and abs(c) <= 10 ** 6 for c in f) and f[-1] == 1,
         'monic of degree 3 to 5')
    n = len(f) - 1; D = _disc(f); need(D != 0, 'repeated roots')
    need(_irreducible(f, budget), 'the polynomial is reducible')
    square = _q_square(D)
    if n == 3: return 'C3' if square else 'S3'
    if n == 4:
        e_, d_, c_, b_ = f[0], f[1], f[2], f[3]
        cub = [-(b_ * b_ * e_ - 4 * c_ * e_ + d_ * d_), b_ * d_ - 4 * e_, -c_, 1]
        rr = _rational_roots(cub)
        if not rr: return 'A4' if square else 'S4'
        if len(rr) == 3: return 'V4'
        t = next(iter(rr))
        return 'C4' if _q_square((t * t - 4 * e_) * D) and _q_square((b_ * b_ - 4 * (c_ - t)) * D) else 'D4'
    types = set()
    for p in range(3, P + 1):
        if not is_prime(p, budget) or D % p == 0: continue
        budget.use(n * n * p.bit_length()); types.add(tuple(factor_degrees_mod(f, p)))
    if (1, 1, 1, 2) in types: return 'S5'
    if square and (1, 1, 3) in types: return 'A5'
    return None


