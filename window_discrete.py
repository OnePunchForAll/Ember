def _convex_position(pts):
    """Whether the points are in strictly convex position (each a vertex of the hull)."""
    n = len(pts)
    for i in range(n):
        for j in range(n):
            if i == j: continue
            side = [_area2(pts[i], pts[j], pts[k]) for k in range(n) if k not in (i, j)]
            if all(s > 0 for s in side) or all(s < 0 for s in side): break
        else:
            return False
    return True


