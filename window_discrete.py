    found = {t: 0 for t in ins}; frontier = {frozenset(ins)}
    for size in range(1, S + 1):
        nxt = set(); last = size == S
        for wires in frontier:
            ws = sorted(wires)
            for i, a in enumerate(ws):
                for b in ws[i:]:
                    for op in range(16):
                        budget.use()
                        t = _gate(op, a, b) & mask
                        if t in wires: continue
                        if t not in found: found[t] = size
                        if not last: nxt.add(wires | {t})
        frontier = nxt
        need(len(frontier) <= 300_000, 'search frontier bound')
    hist = {}
    for t, s in found.items(): hist[str(s)] = hist.get(str(s), 0) + 1
    hist = dict(sorted(hist.items(), key=lambda kv: int(kv[0])))
    hist['more'] = total - len(found)
    return hist


